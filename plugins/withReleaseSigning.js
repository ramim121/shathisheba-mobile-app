const { withAppBuildGradle } = require('@expo/config-plugins');

/**
 * Sign release builds with the Play upload key — without the key ever touching
 * the repository.
 *
 * ## Where the key lives
 *
 * The keystore and its passwords sit outside both repos (they are public on
 * GitHub). Gradle reads four properties, normally from the user-level file
 * `%USERPROFILE%\.gradle\gradle.properties`, or from `-P` flags on one build:
 *
 *     SHATHI_UPLOAD_STORE_FILE=C:/Apps/Digigram/ShathiSheba/Resources/play-store/upload-keystore.jks
 *     SHATHI_UPLOAD_STORE_PASSWORD=...
 *     SHATHI_UPLOAD_KEY_ALIAS=shathisheba-upload
 *     SHATHI_UPLOAD_KEY_PASSWORD=...
 *
 * Forward slashes in the path: Gradle parses the file as Java properties, where
 * `\U` and `\A` are escape sequences and a Windows path arrives mangled.
 *
 * ## What it changes
 *
 * - adds a `release` signing config built from those properties;
 * - points the `release` build type at it **when the properties are present**,
 *   and at the template's debug key otherwise — so an `assembleRelease` test APK
 *   still builds on a machine without the key and still installs over the
 *   sideloaded app (same debug key as every APK shipped so far);
 * - refuses to run `bundleRelease` without the upload key. Play rejects a
 *   debug-signed bundle anyway, but only after a 20-minute build and an upload;
 *   failing before the build starts is cheaper.
 *
 * ## Why a config plugin
 *
 * `/android` is gitignored and regenerated by `expo prebuild`, so a hand edit to
 * `android/app/build.gradle` would silently vanish at the next prebuild and the
 * next bundle would quietly go back to the debug key.
 */
const PROPS = ['SHATHI_UPLOAD_STORE_FILE', 'SHATHI_UPLOAD_STORE_PASSWORD', 'SHATHI_UPLOAD_KEY_ALIAS', 'SHATHI_UPLOAD_KEY_PASSWORD'];
const MARK = '// withReleaseSigning';

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let gradle = cfg.modResults.contents;
    if (gradle.includes(MARK)) return cfg;

    const has = PROPS.map((p) => `project.hasProperty('${p}')`).join(' && ');

    // 1. A release signing config, filled only when every property is set.
    const signingAt = gradle.indexOf('signingConfigs {');
    if (signingAt === -1) throw new Error('withReleaseSigning: no signingConfigs block in app/build.gradle');
    const insertAt = signingAt + 'signingConfigs {'.length;
    gradle =
      gradle.slice(0, insertAt) +
      `
        ${MARK}: the Play upload key, read from gradle.properties outside the repo
        release {
            if (${has}) {
                storeFile file(SHATHI_UPLOAD_STORE_FILE)
                storePassword SHATHI_UPLOAD_STORE_PASSWORD
                keyAlias SHATHI_UPLOAD_KEY_ALIAS
                keyPassword SHATHI_UPLOAD_KEY_PASSWORD
            }
        }` +
      gradle.slice(insertAt);

    // 2. The release build type uses it when present. Only the first
    //    `signingConfig signingConfigs.debug` *after* `release {` inside
    //    buildTypes is replaced — the debug build type keeps the debug key.
    const typesAt = gradle.indexOf('buildTypes {');
    const releaseAt = typesAt === -1 ? -1 : gradle.indexOf('release {', typesAt);
    const target = 'signingConfig signingConfigs.debug';
    const lineAt = releaseAt === -1 ? -1 : gradle.indexOf(target, releaseAt);
    if (lineAt === -1) throw new Error('withReleaseSigning: release build type not found in app/build.gradle');
    gradle =
      gradle.slice(0, lineAt) +
      `signingConfig ((${has}) ? signingConfigs.release : signingConfigs.debug)` +
      gradle.slice(lineAt + target.length);

    // 3. Never produce a debug-signed bundle.
    gradle += `
${MARK}: a Play bundle must be signed with the upload key, so fail before building one without it.
gradle.taskGraph.whenReady { graph ->
    def wantsBundle = graph.allTasks.any { it.path == ':app:bundleRelease' }
    if (wantsBundle && !(${has})) {
        throw new GradleException(
            "bundleRelease needs the Play upload key. Set ${PROPS.join(', ')} " +
            "in %USERPROFILE%/.gradle/gradle.properties (see plugins/withReleaseSigning.js)."
        )
    }
}
`;
    cfg.modResults.contents = gradle;
    return cfg;
  });
};
